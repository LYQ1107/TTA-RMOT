def prepare():
    m=metadata();out=OUTPUT/'stage2';out.mkdir(parents=True,exist_ok=True)
    videos=sorted(m['videos']);inputs=[]
    for v in videos:
        p=SOURCE/'videos'/v/'questions.json'
        a=json.loads(p.read_text())
        inputs.append(dict(video=v,question_sha256=file_sha(p),calls=len(a),rounds=[sum(x['round']==r for x in a) for r in range(1,5)],
            presence_snapshots={str(r):file_sha(p.parent/f'presence_round{r}.npz') for r in range(5)}))
    protocol=dict(version='A100_C4_CAUSAL_V2',seed=0,target='SportsMOT',source='Dance-best',videos=videos,
        query_count=len(m['episodes']),logical_answers=sum(x['calls'] for x in inputs),fixed_evidence=inputs,
        methods=METHODS,reference_FULL='sealed A800 FULL, descriptive only',
        sequence='ordered videos; adapters, optimizer, DS and fast slope persist; source presence snapshots fixed',
        recalc_schedule='produced without GT by matched LoRA; zero-weight arm waits for the same round events',
        no_LoRA_arm='zero-output adapter present, optimizer never stepped; fixed32 score and second fast fit at every matched event',
        initial_anchor='current A100 zero-weight canonical full-video arrays, generated by control before any round; shared exactly by MINUS and zero-update LoRA prefix',
        historical_numerics='A800 frozen margins are descriptive only; no asymmetric A800-to-A100 anchoring in the causal comparison',
        pcd_storage='PCD computed normally but not persisted; only margins are consumed by the original source head',
        primary='official full C4 HOTA; paired video bootstrap 10000 seed0',
        additional='DetA AssA IDF1; per-frame CountMatched with opposite-arm counts and frozen/evolved ranking',
        interpretation='LoRA minus no-weight at matched schedule estimates weight-branch contribution including downstream fast-fit response; no semantic-neuron claim from HOTA alone',
        GT_available_to_generation=False,registered_before_new_GT=True)
    path=out/'preregistration.json'
    if path.exists():assert json.loads(path.read_text())==protocol
    else:atomic_json(path,protocol)
    print(json.dumps(dict(status='REGISTERED',videos=len(videos),queries=len(m['episodes']),calls=protocol['logical_answers'],path=str(path))),flush=True)


def wait_schedule(video,round_index):
    p=OUTPUT/'stage2/SLOW_REPLAY_MATCHED/videos'/video/f'event_{round_index}.json'
    failure=OUTPUT/'stage2/SLOW_REPLAY_MATCHED/FAILED.json'
    while not p.exists():
        if failure.exists():raise RuntimeError('Matched LoRA producer failed: '+failure.read_text())
        time.sleep(1)
    return json.loads(p.read_text())


class CanonicalInputs(FrozenFrameInputs):
    def __init__(self,video,bank,queries):
        folder=OUTPUT/'stage2/canonical'/video
        failure=OUTPUT/'stage2/MINUS_RECALC_ONLY/FAILED.json'
        while not (folder/'ready.json').exists():
            if failure.exists():raise RuntimeError('Canonical producer failed: '+failure.read_text())
            time.sleep(1)
        self.bank,self.queries=bank,queries
        self.observations=np.asarray(bank['observations'])
        self.tracks=sorted({int(t) for f,t in self.observations})
        self.by_track={t:np.flatnonzero(self.observations[:,1]==t) for t in self.tracks}
        self.frame_index={int(t):i for i,t in enumerate(sorted({f for f,t in self.observations}))}
        with np.load(folder/'initial.npz') as a:
            self.margin=a['margin'].copy();self.raw_presence=a['raw_presence'].copy()
            self.utilities=a['utilities'].copy();self.raw_k=a['raw_k'].copy()
        self.decode_seconds=0.;self.score_records=[]


def publish_canonical(fc,video):
    folder=OUTPUT/'stage2/canonical'/video;folder.mkdir(parents=True,exist_ok=True)
    p=folder/'initial.npz';tmp=p.with_suffix('.partial')
    if (folder/'ready.json').exists():
        with np.load(p) as old:
            equal={name:np.array_equal(np.asarray(getattr(fc,name)),old[name])
                   for name in ('margin','raw_presence','utilities','raw_k')}
        atomic_json(folder/'resume_numerical_equivalence.json',dict(all_arrays_bitwise_equal=all(equal.values()),arrays=equal,
            cache_capacity_bytes=fc.cache.max_bytes,GT_used=False))
        assert all(equal.values()), 'A runtime-only cache change must preserve canonical numerical inputs exactly'
        return
    with tmp.open('wb') as f:
        np.savez(f,margin=np.asarray(fc.margin),raw_presence=fc.raw_presence,utilities=fc.utilities,raw_k=fc.raw_k)
        f.flush();__import__('os').fsync(f.fileno())
    tmp.replace(p)
    atomic_json(folder/'ready.json',dict(status='A100_ZERO_WEIGHT_CANONICAL',video=video,optimizer_updates=0,
        checkpoint='official Dance-best',source_head=str(source_head()),initial_arrays_sha256=file_sha(p)))


def run(method,feature_cache_mib=8192):
    access=runtime_guard();torch.set_num_threads(8);torch.manual_seed(0);np.random.seed(0)
    out=OUTPUT/'stage2'/method;out.mkdir(parents=True,exist_ok=True)
    if (out/'predictions_seal.json').exists():
        print(json.dumps(dict(event='ALREADY_SEALED',method=method)),flush=True);return
    protocol=OUTPUT/'stage2/preregistration.json';assert protocol.exists()
    meta=metadata()
    _,em,ds=setup(PRESUPPOSED);slope=1.;temperature=1.;bias=0.;slow=None;model=None;start=0
    saved_path=out/'stream.pt'
    saved=torch.load(saved_path,map_location='cpu',weights_only=False) if saved_path.exists() else None
    if saved:
        start=saved['next_video'];ds=saved['ds'];slope=saved['slope'];temperature=saved['temperature'];bias=saved['bias']
    if method!='MINUS':
        device=torch.device('cuda:0')
        model,tok,transform,loaded=load_student(out/'model_log',device)
        atomic_json(out/'model_load.json',loaded)
    ordered=sorted(meta['videos'])
    for vi,video in enumerate(ordered):
        if vi<start:continue
        video_begin=time.perf_counter();bank=meta['videos'][video]
        queries=[q for q in meta['episodes'] if q['video_id']==video];texts=[q['query_text'] for q in queries]
        directory=out/'videos'/video;directory.mkdir(parents=True,exist_ok=True)
        if model is not None:
            from flex_tta.runtime.frozen_features import FrozenFeatureCache
            ep=episode_from_bank(video,bank,'SportsMOT',transform)
            cache=FrozenFeatureCache(model,ep,tok,device,max_bytes=feature_cache_mib<<20)
            if slow is None:
                slow=SlowAdapterV8(model,cache)
                if saved:
                    slow.adapter.load_state_dict(saved['adapter']);slow.optimizer.load_state_dict(saved['optimizer'])
                    slow.scaler.load_state_dict(saved['scaler']);slow.rng.set_state(saved['slow_rng']);slow.updates=saved['updates']
                    torch.set_rng_state(saved['torch_rng']);torch.cuda.set_rng_state(saved['cuda_rng'])
            else:slow.set_cache(cache)
            fc=FrameCacheV6(model,cache,bank,queries,sorted({int(f) for f,t in bank['observations']}),source_head(),directory/'frame_cache',store_pcd=False)
            fc.score(model_step=slow.updates)
            if method=='MINUS_RECALC_ONLY':
                assert slow.updates==0
                publish_canonical(fc,video)
            elif slow.updates==0:
                frozen=CanonicalInputs(video,bank,queries)
                anchor_unupdated_replay(fc,frozen,directory)
        else:fc=CanonicalInputs(video,bank,queries)
        params=json.loads((SOURCE/'videos'/video/'em_video_start.json').read_text())
        fraction,p,_=fc.decode(temperature,bias);lengths=[len(fc.by_track[t]) for t in fc.tracks]
        state=belief_state(PRESUPPOSED,fc.track_means(),fraction,p.max(1),track_lengths=lengths,
            rho_hat=params['rho_hat'],pi_strata=params['pi_strata'],slope=slope)
        state.recompute_presence(ds.values)
        with np.load(SOURCE/'videos'/video/'presence_round0.npz') as snap:state.freeze_presence_snapshot(snap)
        answers=json.loads((SOURCE/'videos'/video/'questions.json').read_text())
        tid={t:i for i,t in enumerate(fc.tracks)};qid={q['expression_id']:i for i,q in enumerate(queries)}
        group=exclusive_group(texts,'SportsMOT');had_sample=False;rounds=[]
        for r in range(1,5):
            rb=time.perf_counter();state.recompute_presence(ds.values)
            for a in (a for a in answers if a['round']==r):
                ingest(state,qid[a['query_id']],tid[a['track_id']],a['kind'],a,a['information_gain'],replay=True)
                ds.add((video,a['query_id'],a['track_id']),a['effective_view'],a['yes_probability']>=.5)
            t=time.perf_counter();ds.fit();ds_seconds=time.perf_counter()-t;state.recompute_presence(ds.values)
            with np.load(SOURCE/'videos'/video/f'presence_round{r}.npz') as snap:state.freeze_presence_snapshot(snap)
            t=time.perf_counter();fast=fast_step_v8(state,fc.raw_presence,temperature=temperature,bias=bias)
            temperature,bias=fast['temperature'],fast['bias'];fc.refresh(state,temperature,bias,retain_sampled=had_sample)
            fast_seconds=time.perf_counter()-t
            slow_log=dict(status='DISABLED',optimizer_updates=0,GPU_seconds=0.)
            schedule_wait_seconds=0.
            if method=='SLOW_REPLAY_MATCHED':
                slow_log=slow.slow_step(state,fc.tracks,texts,exclusive=group)
                event=dict(video=video,round=r,recalculate=bool(slow_log['optimizer_updates']),optimizer_updates=slow_log['optimizer_updates'],total_updates=slow.updates)
                atomic_json(directory/f'event_{r}.json',event)
            elif method=='MINUS_RECALC_ONLY':
                wait_begin=time.perf_counter()
                event=wait_schedule(video,r)
                schedule_wait_seconds=time.perf_counter()-wait_begin
                slow_log=dict(status='ZERO_WEIGHT_CONTROL',optimizer_updates=0,GPU_seconds=0.,matched_event=event)
            else:event=dict(recalculate=False)
            recalc_seconds=0.
            if event['recalculate']:
                t=time.perf_counter();fc.score(sampled=True,model_step=slow.updates);had_sample=True
                fc.refresh_sampled(state,temperature,bias)
                after=fast_step_v8(state,fc.raw_presence,temperature=temperature,bias=bias)
                temperature,bias=after['temperature'],after['bias'];fc.refresh(state,temperature,bias,retain_sampled=True)
                fast['after_recalc']=after;recalc_seconds=time.perf_counter()-t
            row=dict(video=video,video_index=vi,round=r,method=method,calls=sum(a['round']==r for a in answers),
                fast=fast,slow=slow_log,ds=ds.receipt(),fast_wall_seconds=fast_seconds,DS_wall_seconds=ds_seconds,
                recalc_and_refit_wall_seconds=recalc_seconds,round_wall_seconds=time.perf_counter()-rb,
                matched_schedule_wait_seconds=schedule_wait_seconds,
                positive_pairs=int((state.pseudo_labels()==1).sum()),negative_pairs=int((state.pseudo_labels()==0).sum()))
            append_json(out/'rounds.jsonl',row);rounds.append(row)
            print(json.dumps(dict(event='ROUND_DONE',method=method,video_index=vi,video=video,round=r,updates=slow_log['optimizer_updates'],recalc=event['recalculate'],seconds=row['round_wall_seconds'])),flush=True)
        posterior=state.posterior;chosen=posterior>.5;chosen[state.output_absence()]=False
        if group:chosen &= np.arange(len(texts))[:,None]==posterior.argmax(axis=0)[None]
        mask=np.zeros((len(queries),len(bank['observations'])),dtype=bool);calibrated=expit(fc.raw_presence/temperature+bias)
        for q,text in enumerate(texts):
            motion='MOTION' in expression_types(text)
            for j,(frame,track) in enumerate(bank['observations']):mask[q,j]=chosen[q,tid[track]] and (not motion or calibrated[q,fc.frame_index[frame]]>=.5)
        np.save(directory/'mask.npy',mask)
        historical_mask_differences=(int(np.count_nonzero(mask!=np.load(SOURCE/'videos'/video/'mask.npy')))
                                     if method=='MINUS' else None)
        np.savez(directory/'belief.npz',posterior=posterior,prior=state.prior,evidence=state.evidence,tracks=np.asarray(fc.tracks),
            queries=np.asarray([q['expression_id'] for q in queries]),fractions=state.fractions,intercept=state.a,slope=state.slope,
            pseudo_labels=state.pseudo_labels(),asked_mask=state.asked_mask)
        if model is not None:
            fc.close()
            if method=='MINUS_RECALC_ONLY':
                assert slow.updates==0
                assert all(torch.equal(p,initial) for p,initial in zip(slow.parameters,slow.initial_trainable))
        receipt=dict(video=video,method=method,questions=len(answers),wall_seconds=time.perf_counter()-video_begin,
            initial_and_recalc_score_records=fc.score_records,decode_wall_seconds=fc.decode_seconds,
            slow_updates=sum(x['slow']['optimizer_updates'] for x in rounds),rounds=rounds,GT_open_attempts=len(access),
            fixed_evidence_sha256=file_sha(SOURCE/'videos'/video/'questions.json'))
        receipt['historical_MINUS_numerical_difference_rows']=historical_mask_differences
        receipt['feature_cache_mib']=feature_cache_mib if model is not None else None
        receipt['frozen_encoder_cache_stats']=dict(cache.stats) if model is not None else None
        atomic_json(directory/'receipt.json',receipt)
        slope=state.slope
        saved=dict(next_video=vi+1,ds=ds,slope=slope,temperature=temperature,bias=bias,
            adapter=slow.adapter.state_dict() if slow else None,optimizer=slow.optimizer.state_dict() if slow else None,
            scaler=slow.scaler.state_dict() if slow else None,slow_rng=slow.rng.get_state() if slow else None,
            updates=slow.updates if slow else 0,torch_rng=torch.get_rng_state(),cuda_rng=torch.cuda.get_rng_state() if slow else None)
        tmp=saved_path.with_suffix('.partial');torch.save(saved,tmp);tmp.replace(saved_path)
        del fc
        print(json.dumps(dict(event='VIDEO_DONE',method=method,video_index=vi,video=video,seconds=receipt['wall_seconds'])),flush=True)
    mask=np.zeros(meta['candidate_query_rows'],dtype=bool)
    for video in ordered:
        local=np.load(out/'videos'/video/'mask.npy')
        for qi,q in enumerate(q for q in meta['episodes'] if q['video_id']==video):mask[q['start']:q['stop']]=local[qi]
    from flex_uda.presence.predictions import seal_mask
    assert not access
    receipts=[json.loads((out/'videos'/v/'receipt.json').read_text()) for v in ordered]
    attempts=[json.loads(p.read_text()) for p in sorted((out/'attempts').glob('*/supervisor_receipt.json'))]
    previous_wall=sum(r['wall_seconds'] for r in attempts)
    seal_mask(out,meta,mask,target='SportsMOT',model='Dance-best',method=method,GT_open_attempts=0,
        extra=dict(version='A100_C4_CAUSAL_V2',pair='C4',rho=.3,teacher=dict(logical_calls=sum(x['questions'] for x in receipts),
            replayed_answers=sum(x['questions'] for x in receipts),new_calls=0,cache_hits=0,forward_seconds=0.),
            margin_input=dict(kind='A100 current zero-weight canonical inputs',per_video_ready_sha256={v:file_sha(OUTPUT/'stage2/canonical'/v/'ready.json') for v in ordered}),
            protocol_sha256=file_sha(protocol),LoRA_enabled=method=='SLOW_REPLAY_MATCHED',
            LoRA_GPU_seconds=sum(r['slow']['GPU_seconds'] for v in receipts for r in v['rounds']),
            rescore_GPU_seconds=sum(r['GPU_seconds'] for v in receipts for r in v['initial_and_recalc_score_records']),
            video_transductive=True,strict_frame_causal=False,wall_seconds=previous_wall+time.perf_counter()-PROCESS_STARTED,
            this_attempt_wall_seconds=time.perf_counter()-PROCESS_STARTED,previous_attempt_wall_seconds=previous_wall,
            prior_attempts=attempts,feature_cache_mib=feature_cache_mib,
            execution_cost_note='Replay experiment excludes new teacher work; not a deployment end-to-end cost'))
    print(json.dumps(dict(event='CAUSAL_ARM_SEALED',method=method,seconds=time.perf_counter()-PROCESS_STARTED)),flush=True)


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--prepare',action='store_true');p.add_argument('--method',choices=METHODS)
    p.add_argument('--feature-cache-mib',type=int,default=8192)
    a=p.parse_args()
    if a.prepare:prepare()
    else:
        try:run(a.method,a.feature_cache_mib)
        except BaseException as e:
            atomic_json(OUTPUT/'stage2'/a.method/'FAILED.json',dict(error=repr(e)))
            raise
