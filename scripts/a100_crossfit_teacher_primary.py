def prepare():
    from flex_uda.a100.mechanism import generation_guard
    from flex_uda.active.crossfit_teacher_feedback import group_folds
    guard=generation_guard();prior=parent.registration()
    assert (parent.OUT/'independent_sealed_prediction_audit.json').is_file()
    refs={};initials={};splits=[]
    for case in prior['cases']:
        pair=case['pair']
        for name in parent.COMPARATORS:
            for leaf in ('scores.npy','mask.npy','predictions_seal.json'):
                path=reference_folder(pair,name)/leaf;refs[str(path)]=file_sha(path)
        path=parent.OUT/pair/'initial_observer.json';initials[str(path)]=file_sha(path)
        keys=json.loads((parent.parent.OUT/pair/'row_keys.json').read_text())['keys']
        folds=group_folds(keys)
        splits.append(dict(pair=pair,fold_sizes=[int((folds==k).sum()) for k in (0,1)],
                           split_sha256=hashlib.sha256(folds.tobytes()).hexdigest()))
    plan=dict(status='PREREGISTERED_COMPLETE_GROUP_DISJOINT_VISUAL_FEEDBACK_PRIMARY',
        primary=PRIMARY,comparators=COMPARATORS,cases=prior['cases'],splits=splits,
        source_sha256={name:file_sha(ROOT/name) for name in SOURCES},
        parent_registration_sha256=file_sha(parent.PLAN),reused_prediction_sha256=refs,
        initial_observer_sha256=initials,parent_ordinary_audit_sha256=file_sha(parent.OUT/'independent_sealed_prediction_audit.json'),
        hypothesis='Image priors generated by a solver without direct training on the current official track can provide less self-reinforcing teacher-noise feedback than in-sample joint fitting.',
        human_visual_inspiration='Use visual experience from other candidate tracks to question an interpretation of this candidate, while maintaining complete object/state inputs.',
        classical_idea='Group-disjoint prediction and latent observation models; no claim that agreement or a classical theorem certifies semantic truth.',
        split_rule='Deterministic greedy two-way balancing of entire(video,officialTrackID)groups, sorted by group size then SHA. All queries/frames of one provided track stay together; no teacher answer or GT used to split.',
        split_limit='Different official tracks can contain the same real person. Global R updates couple the folds indirectly; no statistical independence claim.',
        observer='Exact previous semantic8-pattern table and8/2 marginal prior; no confidence-to-truth assumption. Same teacher-only initialization reused exactly.',
        ordinary_bootstrap='Each of two identical5508/128/128 heads fits mean soft teacher on its own fold for6000..16000 steps, proper excessKL<=.005, seed0. Saved copies define a fully trained split-ensemble opponent.',
        feedback='Copy ordinary bootstrap heads; four R/S rounds. R receives opposite-fold image priors. Each S fits only its own fold using opposite-fold posterior targets,500/500/500/4000 steps. Joint pair proposal backtracked/restored on penalized opposite-fold observed-objective decrease.',
        final_solver='One identical5508/128/128 head fits all corrected posterior targets,6000..16000 steps/proper excessKL<=.005; fixed final state, no GT/checkpoint search.',
        new_comparator='Probability-mean ensemble of the exact two adequate pre-feedback fold heads, stable logit computation; no rawteacher sample discarded across the ensemble.',
        same_information_teacher_budget_architecture_and_seed=True,
        compute='At least29000 neural optimizer steps/case including12000 ordinary bootstrap,11000 pair proposals,6000 final head. Adaptation compute exceeds a single ordinary head; no equal-time or speedup claim.',
        execution='GPU0/1/3 split heads and predictions; sharedGPU2 final heads fraction.10, existing inference service preserved.',
        raw_records=33,dual_count_records=60,official_statistical_records=93,paired_effects=90,CountSelf_exact_aliases=33,
        success_screen='Same strict main screen: raw and BOTH CountMatched effects positive against ALL10 controls in EVERY first-video case.',
        all93_outputs_sealed_before_current_study_GT=True,no_new_module_ablation_matrix=True,
        new_teacher_GPU_calls=0,neural_seeds=[0],all_data_DEV=True,prior_evaluation_exposure_disclosed=True,
        input_scope=prior['auxiliary_scope'],source_features_prepaid=True,
        no_six_setting_three_contribution_online_or_fresh_cost_claim=True,goal_status='ACTIVE')
    assert not guard
    atomic_json(PLAN,plan);atomic_json(PUBLIC/(STEM+'_registration.json'),plan)
    print(json.dumps(dict(status=plan['status'],pins=len(SOURCES),splits=splits)),flush=True)


def registration():
    plan=json.loads(PLAN.read_text());parent.registration()
    assert file_sha(parent.PLAN)==plan['parent_registration_sha256']
    assert file_sha(parent.OUT/'independent_sealed_prediction_audit.json')==plan['parent_ordinary_audit_sha256']
    for name,sha in plan['source_sha256'].items(): assert file_sha(ROOT/name)==sha,name
    for name,sha in {**plan['reused_prediction_sha256'],**plan['initial_observer_sha256']}.items(): assert file_sha(name)==sha,name
    return plan


def final_worker():
    from flex_uda.active.deterministic_observation_runtime import configure_before_cuda
    configure_before_cuda()
    import numpy as np
    import torch
    from flex_uda.active.joint_teacher_noise import make_solver,fit_solver
    from flex_uda.active.crossfit_teacher_feedback import save_checkpoint,cpu_state
    from flex_uda.a100.mechanism import generation_guard
    plan=registration();guard=generation_guard()
    torch.set_num_threads(2);torch.cuda.set_device(0);torch.cuda.set_per_process_memory_fraction(.10)
    for case in plan['cases']:
        folder=OUT/case['pair'];path=folder/'final_head.pt'
        if path.exists():
            saved=torch.load(path,map_location='cpu',weights_only=False)
            assert saved['registration_sha256']==file_sha(PLAN) and saved['fit']['adequate_passed']
            continue
        while not (folder/'pair_complete.json').exists():
            failure=folder/'failed.json'
            if failure.exists(): raise RuntimeError(failure.read_text())
            time.sleep(2)
        with np.load(parent.input_path(case['pair'])) as data: features=data['features']
        done=json.loads((folder/'pair_complete.json').read_text())
        assert done['target_sha256']==file_sha(folder/'final_targets.npy')
        assert done['registration_sha256']==file_sha(PLAN) and done['GT_open_attempts']==0
        target=np.load(folder/'final_targets.npy')
        model=make_solver('cuda:0')
        fit=fit_solver(model,features,target,'cuda:0',steps=6000,adequate=True)
        save_checkpoint(path,dict(model=cpu_state(model),fit=fit,seed=0,data_sha256=case['data_sha256'],
                        target_sha256=done['target_sha256'],registration_sha256=file_sha(PLAN)))
        print(json.dumps(dict(status='CROSSFIT_FINAL_SOLVER_COMPLETE',pair=case['pair'],steps=fit['steps'],excess_KL=fit['excess_KL'])),flush=True)
        del model
    assert not guard
    atomic_json(OUT/'final_GPU2_complete.json',dict(status='THREE_FINAL_HEADS_COMPLETE_NO_GT',GT_open_attempts=0))


def worker(pair):
    from flex_uda.active.deterministic_observation_runtime import configure_before_cuda
    execution=configure_before_cuda()
    import numpy as np
    import torch
    from scipy.special import logsumexp
    from flex_uda.active.crossfit_teacher_feedback import train_pair
    from flex_uda.active.joint_teacher_noise import make_solver
    from flex_uda.active.factor_rsi_learning import Inputs
    from flex_uda.active.joint_observation_inputs import JointObservationVideo,use_verified_local_features
    from flex_uda.presence.predictions import seal_mask,verify_predictions
    from flex_uda.a100.mechanism import generation_guard,PAIRS
    from scripts.a100_factor_rsi_primary_quality import subset_metadata,projection
    plan=registration();guard=generation_guard();folder=OUT/pair
    if (folder/'main_completion.json').exists(): return
    started=time.perf_counter()
    torch.set_num_threads(2);torch.cuda.set_device(0);torch.cuda.set_per_process_memory_fraction(.35)
    use_verified_local_features()
    case=next(c for c in plan['cases'] if c['pair']==pair)
    with np.load(parent.input_path(pair)) as data: features,probability=data['features'],data['probability']
    keys=json.loads((parent.parent.OUT/pair/'row_keys.json').read_text())['keys']
    initial=json.loads((parent.OUT/pair/'initial_observer.json').read_text())
    models,state=train_pair(features,probability,keys,initial['state'],folder,'cuda:0',file_sha(PLAN),case['data_sha256'])
    del models
    while not (folder/'final_head.pt').exists():
        if (OUT/'final_failed.json').exists(): raise RuntimeError((OUT/'final_failed.json').read_text())
        time.sleep(2)
    final=torch.load(folder/'final_head.pt',map_location='cpu',weights_only=False)
    assert final['registration_sha256']==file_sha(PLAN) and final['data_sha256']==case['data_sha256']
    heads=[]
    for saved in [final,*[torch.load(folder/('ordinary_fold'+str(k)+'.pt'),map_location='cpu',weights_only=False) for k in (0,1)]]:
        model=make_solver('cuda:0');model.load_state_dict(saved['model']);model.eval();heads.append(model)
    video=JointObservationVideo(pair,case['evaluated_video']);inputs=Inputs(video)
    queries={r['expression_id']:i for i,r in enumerate(video.queries)};tracks={int(t):i for i,t in enumerate(video.tracks)}
    points=[i for i,row in enumerate(keys) if row[0]==video.video]
    records=[dict(local_query=queries[keys[i][1]],local_track=tracks[int(keys[i][2])],frame_id=int(keys[i][3]),track_id=int(keys[i][2])) for i in points]
    assert np.array_equal(parent.parent.pack(inputs.arrays(records)),features[points])
    scores={n:np.empty((len(video.queries),len(video.obs)),dtype='float32') for n in (PRIMARY,SPLIT)}
    with torch.no_grad():
        for qi in range(len(video.queries)):
            for begin in range(0,len(video.obs),512):
                rows=np.arange(begin,min(begin+512,len(video.obs)))
                records=[dict(local_query=qi,local_track=int(video.columns[r]),frame_id=int(video.obs[r,0]),track_id=int(video.obs[r,1])) for r in rows]
                x=torch.as_tensor(parent.parent.pack(inputs.arrays(records)),device='cuda:0')
                values=[model(x).cpu().numpy() for model in heads]
                scores[PRIMARY][qi,rows]=values[0]
                z=np.stack(values[1:]).astype('float64')
                scores[SPLIT][qi,rows]=logsumexp(-np.logaddexp(0,-z),axis=0)-logsumexp(-np.logaddexp(0,z),axis=0)
    for name in parent.COMPARATORS: scores[name]=np.load(reference_folder(pair,name)/'scores.npy')
    bits={n:z>0 for n,z in scores.items()};metadata=subset_metadata(case['target'],case['evaluated_video']);tasks=[]
    for name in METHODS:
        if name in parent.COMPARATORS:
            root=reference_folder(pair,name)
            assert np.array_equal(np.load(root/'mask.npy'),bits[name]);verify_predictions(root)
        else:
            root=folder/'predictions'/name;root.mkdir(parents=True,exist_ok=True)
            assert np.isfinite(scores[name]).all()
            np.save(root/'scores.npy',scores[name]);np.save(root/'mask.npy',bits[name])
            assert np.array_equal(projection(scores[name],bits[name],video.obs),bits[name])
            seal_mask(root,metadata,bits[name].flatten(),target=case['target'],model=PAIRS[pair][0],method=name,
                      GT_open_attempts=len(guard),extra=dict(seed=0,full_raw_logits_retained=True,
                      matched_data_sha256=case['data_sha256'],no_new_teacher_calls=True))
        tasks.append(dict(pair=pair,method=name,folder=str(root)))
    for rank,count in [(PRIMARY,n) for n in COMPARATORS]+[(n,PRIMARY) for n in COMPARATORS]:
        name=rank+'__AT_'+count+'_COUNT';root=folder/'predictions'/name
        selected=projection(scores[rank],bits[count],video.obs)
        seal_mask(root,metadata,selected.flatten(),target=case['target'],model=PAIRS[pair][0],method=name,
                  GT_open_attempts=len(guard),extra=dict(rank_method=rank,count_method=count,
                  counts_equal_per_query_frame=True,counts_from_GT=False))
        tasks.append(dict(pair=pair,method=name,folder=str(root)))
    assert len(tasks)==31 and not guard
    atomic_json(folder/'main_completion.json',dict(status='SEALED_ALL31_CROSSFIT_CASE_OUTPUTS_NO_GT',tasks=tasks,
                GT_open_attempts=0,execution=execution,final_fit=final['fit'],rounds=state['rounds'],
                wall_seconds=time.perf_counter()-started,not_full_cold_deployment=True))


def main():
    plan=registration();assert (OUT/'contract.json').is_file()
    supervisor=OUT/'supervisor';supervisor.mkdir(parents=True,exist_ok=True)
    pending=[(gpu,c) for gpu,c in zip((0,1,3),plan['cases']) if not (OUT/c['pair']/'main_completion.json').exists()]
    for gpu,case in pending:
        pids=subprocess.check_output(['nvidia-smi','-i',str(gpu),'--query-compute-apps=pid','--format=csv,noheader,nounits'],text=True).strip()
        used=int(subprocess.check_output(['nvidia-smi','-i',str(gpu),'--query-gpu=memory.used','--format=csv,noheader,nounits'],text=True).strip())
        assert not pids and used<512,(gpu,pids,used)
    jobs=[]
    if any(not (OUT/c['pair']/'final_head.pt').exists() for c in plan['cases']):
        used=int(subprocess.check_output(['nvidia-smi','-i','2','--query-gpu=memory.used','--format=csv,noheader,nounits'],text=True).strip())
        total=int(subprocess.check_output(['nvidia-smi','-i','2','--query-gpu=memory.total','--format=csv,noheader,nounits'],text=True).strip())
        residents=subprocess.check_output(['nvidia-smi','-i','2','--query-compute-apps=pid,process_name,used_gpu_memory','--format=csv,noheader,nounits'],text=True).strip()
        assert total-used>=8192,(used,total)
        atomic_json(supervisor/'GPU2_shared_preflight.json',dict(used_MiB=used,total_MiB=total,residents=residents,
                    memory_fraction=.10,user_authorized_sharing=True,all_existing_processes_preserved=True))
        jobs.append(start(supervisor,'FINAL_GPU2',['--final-worker'],2))
    for gpu,case in pending: jobs.append(start(supervisor,case['pair'],['--worker',case['pair']],gpu))
    failures=[]
    for process,stream,log,label in jobs:
        code=process.wait();stream.close()
        if code: failures.append(dict(role=label,exit_code=code,tail=log.read_text()[-5000:]))
    if failures: raise RuntimeError(failures)
    from flex_uda.presence.predictions import verify_predictions
    tasks=[]
    for case in plan['cases']:
        done=json.loads((OUT/case['pair']/'main_completion.json').read_text())
        assert done['GT_open_attempts']==0;tasks.extend(done['tasks'])
    assert len(tasks)==93
    for task in tasks: verify_predictions(task['folder'])
    atomic_json(OUT/'all93_sealed_before_GT.json',dict(tasks=tasks,GT_open_attempts=0,registration_sha256=file_sha(PLAN)))
    print('ALL93_CROSSFIT_OUTPUTS_SEALED_ISOLATED_OFFICIAL_EVALUATION',flush=True)
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool: completed=list(pool.map(parent.parent.evaluate_one,tasks))
    results={c['pair']:{} for c in plan['cases']}
    for task,value in completed: results[task['pair']][task['method']]=value
    comparisons=[]
    for pair,values in results.items():
        primary=values[PRIMARY]['HOTA_unrounded']
        for other in COMPARATORS:
            reference=values[other]['HOTA_unrounded']
            comparisons.append(dict(pair=pair,comparator=other,primary_HOTA=primary,ordinary_HOTA=reference,
              raw_delta_HOTA=primary-reference,
              primary_at_ordinary_count_delta_HOTA=values[PRIMARY+'__AT_'+other+'_COUNT']['HOTA_unrounded']-reference,
              ordinary_at_primary_count_delta_HOTA=primary-values[other+'__AT_'+PRIMARY+'_COUNT']['HOTA_unrounded']))
    eligible=all(min(r['raw_delta_HOTA'],r['primary_at_ordinary_count_delta_HOTA'],r['ordinary_at_primary_count_delta_HOTA'])>0 for r in comparisons)
    atomic_json(OUT/'quality_results.json',dict(status='COMPLETE_CROSSFIT_VISUAL_TEACHER_PRIMARY',results=results,
                comparisons=comparisons,candidate_eligible_for_larger_screen=eligible,all_data_DEV=True,
                no_six_setting_or_three_innovation_or_fresh_cost_claim=True,goal_status='ACTIVE'))
    for flag in ('--collect','--reproduce'):
        subprocess.run([sys.executable,'-u','scripts/a100_crossfit_teacher_statistics.py',flag],cwd=ROOT,check=True)
    print(json.dumps(dict(status='COMPLETE_CROSSFIT_PRIMARY_ALL93_REPRODUCED',comparisons=comparisons)),flush=True)


def start(folder,label,args,gpu):
    log=folder/(label+'.log');stream=log.open('a',buffering=1)
    process=subprocess.Popen([sys.executable,'-u',str(Path(__file__)),*args],cwd=ROOT,
        stdin=subprocess.DEVNULL,stdout=stream,stderr=subprocess.STDOUT,
        env=dict(os.environ,CUDA_VISIBLE_DEVICES=str(gpu),OMP_NUM_THREADS='2',OPENBLAS_NUM_THREADS='2'))
    atomic_json(folder/(label+'_launch.json'),dict(pid=process.pid,GPU=gpu,role=label))
    print(json.dumps(dict(status='STARTED_CROSSFIT_PRIMARY_ROLE',role=label,GPU=gpu,pid=process.pid)),flush=True)
    return process,stream,log,label


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--prepare',action='store_true')
    parser.add_argument('--worker');parser.add_argument('--final-worker',action='store_true');args=parser.parse_args()
    try:
        if args.prepare: prepare()
        elif args.worker: worker(args.worker)
        elif args.final_worker: final_worker()
        else: main()
    except Exception as error:
        if args.worker: atomic_json(OUT/args.worker/'failed.json',dict(error=repr(error)))
        if args.final_worker: atomic_json(OUT/'final_failed.json',dict(error=repr(error)))
        raise
